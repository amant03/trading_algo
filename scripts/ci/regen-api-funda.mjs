// Regenerates frontend/api/funda.ts as a single self-contained lambda file:
//   [engine source = frontend/src/lib/funda.ts] + [relay = scripts/ci/api-funda-relay.ts.tpl]
// Keep Vercel ("api/*.ts cannot use relative imports") happy. Run after ANY
// change to frontend/src/lib/funda.ts or the relay template:
//   node scripts/ci/regen-api-funda.mjs
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const engine = readFileSync(join(root, 'frontend', 'src', 'lib', 'funda.ts'), 'utf8');
const relay = readFileSync(join(root, 'scripts', 'ci', 'api-funda-relay.ts.tpl'), 'utf8');

const outPath = join(root, 'frontend', 'api', 'funda.ts');
mkdirSync(dirname(outPath), { recursive: true });
writeFileSync(
  outPath,
  `// AUTO-GENERATED by scripts/ci/regen-api-funda.mjs — do not edit by hand.
// Regenerate via:  node scripts/ci/regen-api-funda.mjs
// Engine:   frontend/src/lib/funda.ts
// Relay:    scripts/ci/api-funda-relay.ts.tpl
${engine}
${relay}
`,
  'utf8',
);
console.log(`wrote ${outPath} (${engine.length} engine + ${relay.length} relay chars)`);